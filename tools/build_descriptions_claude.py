    print("=== validation ===")
    attr_set = set(ATTRS_LIST)
    obj_set = set(OBJS_LIST)
    flags = []
    for a, subs in ATTRS.items():
        for i, s in enumerate(subs):
            words = set(re.findall(r"[a-z]+", s.lower()))
            # other attribute words leaked
            bad_attrs = (words & attr_set) - {a}
            # object names leaked
            bad_objs = words & obj_set
            if bad_attrs or bad_objs:
                flags.append((a, i, sorted(bad_attrs), sorted(bad_objs), s))
    for o, subs in OBJS.items():
        for i, s in enumerate(subs):
            words = set(re.findall(r"[a-z]+", s.lower()))
            # attribute words leaked into object description
            bad_attrs = words & attr_set
            if bad_attrs:
                flags.append((o, i, sorted(bad_attrs), [], s))

    if flags:
        print(f"FLAGGED {len(flags)} description(s) with leakage:")
        for prim, i, bad_a, bad_o, s in flags[:50]:
            marks = []
            if bad_a: marks.append(f"attrs={bad_a}")
            if bad_o: marks.append(f"objs={bad_o}")
            print(f"  [{prim}#{i}] {' '.join(marks)} :: {s}")
        if len(flags) > 50:
            print(f"  ... and {len(flags)-50} more")
